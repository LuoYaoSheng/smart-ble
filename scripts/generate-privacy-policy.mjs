import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const policy = fs.readFileSync(path.join(root, 'docs/privacy.md'), 'utf8');
const escape = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const body = policy.trim().split(/\n\n+/).map(block => {
  const heading = block.match(/^(#{1,3}) (.*)$/);
  if (heading) return `<h${heading[1].length}>${escape(heading[2])}</h${heading[1].length}>`;
  return `<p>${escape(block).replace(/\[([^\]]+)\]\((https:\/\/[^)]+)\)/g, '<a href="$2" rel="noreferrer">$1</a>').replaceAll('\n', '<br>')}</p>`;
}).join('\n');
const outputs = {
  'apps/uniapp/config/privacy-policy.js': `// Generated by scripts/generate-privacy-policy.mjs from docs/privacy.md.\nexport const PRIVACY_POLICY = ${JSON.stringify(policy)};\n`,
  'apps/uniapp/static/privacy.html': `<!doctype html>\n<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'"><title>BLE Toolkit+ 隐私说明</title><style>body{font:16px/1.7 system-ui,sans-serif;margin:24px auto;padding:0 20px;max-width:760px;color:#203040;background:#fff}h1{font-size:26px}h2{font-size:20px;margin-top:28px}a{color:#1b6dff;overflow-wrap:anywhere}</style></head><body>\n${body}\n</body></html>\n`
};
for (const [relative, content] of Object.entries(outputs)) {
  const destination = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== content) throw new Error(`Privacy policy drift: ${relative}`);
  } else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, content);
  }
}
console.log('Privacy policy mirrors PASS');
