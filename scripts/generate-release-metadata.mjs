#!/usr/bin/env node
/**
 * 从根 VERSION + release/release-state.json 确定性生成 PREVIEW Release Metadata。
 * 不写当前时间；不自动探测 Git commit；不访问网络。
 *
 * Usage:
 *   node scripts/generate-release-metadata.mjs
 *   node scripts/generate-release-metadata.mjs --check
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const SEMVER = /^[0-9]+\.[0-9]+\.[0-9]+$/;

const OUT_PATHS = {
  manifest: 'release/release-manifest.json',
  docsLatest: 'docs/public/release/latest.json',
  appJson: 'apps/uniapp/config/release-metadata.generated.json',
  appJs: 'apps/uniapp/config/release-metadata.generated.js',
  appleJson: 'apps/ios/Sources/Resources/Release/release-manifest.json',
  flutterDart: 'apps/flutter/lib/core/config/release_metadata_generated.dart',
  androidKotlin:
    'apps/android/app/src/main/java/com/smartble/core/config/ReleaseMetadataGenerated.kt',
};

function readText(rel) {
  return readFileSync(resolve(ROOT, rel), 'utf8');
}

function readJson(rel) {
  return JSON.parse(readText(rel));
}

function stableStringify(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function readVersion() {
  if (!existsSync(resolve(ROOT, 'VERSION'))) {
    throw new Error('仓库根 VERSION 单源文件缺失');
  }
  const raw = readText('VERSION').replace(/^\uFEFF/, '');
  const lines = raw.split(/\r?\n/);
  if (lines.length < 1) throw new Error('VERSION 为空');
  const version = lines[0].trim();
  if (!SEMVER.test(version)) {
    throw new Error(`VERSION 不是合法 SemVer MAJOR.MINOR.PATCH: ${JSON.stringify(version)}`);
  }
  if (lines.length === 2 && lines[1] !== '') {
    throw new Error('VERSION 必须恰好一行内容并以 LF 结尾');
  }
  if (lines.length > 2 || (lines.length === 2 && lines[1] !== '')) {
    // allow trailing single newline only: "1.0.5\n" → ["1.0.5", ""]
    if (!(lines.length === 2 && lines[1] === '')) {
      throw new Error('VERSION 只能包含一行版本号');
    }
  }
  return version;
}

function readBuildCode() {
  const manifest = readJson('apps/uniapp/manifest.json');
  const code = Number(manifest.versionCode);
  if (!Number.isInteger(code) || code < 1) {
    throw new Error(`apps/uniapp/manifest.json versionCode 非法: ${manifest.versionCode}`);
  }
  return code;
}

function applyOverrides(state) {
  const next = { ...state };
  if (process.env.RELEASE_TAG) next.release_tag = process.env.RELEASE_TAG;
  if (process.env.RELEASE_COMMIT) next.commit = process.env.RELEASE_COMMIT;
  if (process.env.RELEASE_BUILT_AT) next.built_at = process.env.RELEASE_BUILT_AT;
  return next;
}

function buildManifest(version, buildCode, state) {
  if (Object.prototype.hasOwnProperty.call(state, 'app_version')) {
    throw new Error('release-state.json 不得保存 app_version（版本唯一事实源是根 VERSION）');
  }
  if (!Array.isArray(state.artifacts) || state.artifacts.length !== 0) {
    // PREVIEW 本轮强制空产物；后续 RELEASE-PIPELINE 可注入非空
    if (!process.env.RELEASE_ALLOW_ARTIFACTS) {
      if (!Array.isArray(state.artifacts)) {
        throw new Error('release-state.json artifacts 必须是数组');
      }
      for (const a of state.artifacts) {
        if (!a?.url || !a?.sha256 || a.url === '' || a.sha256 === '') {
          throw new Error('Artifact 不得使用空 url/sha256 冒充；无产物时 artifacts=[]');
        }
      }
    }
  }

  const surfaces = state.public_surfaces || {};
  for (const [key, surface] of Object.entries(surfaces)) {
    if (surface?.capability_status === 'REFERENCE') {
      throw new Error(`${key}: REFERENCE 是角色，不得作为 capability_status`);
    }
  }

  return {
    schema_version: '1.0',
    channel: state.channel,
    release_tag: state.release_tag ?? null,
    app_version: version,
    app_build_code: buildCode,
    commit: state.commit ?? null,
    built_at: state.built_at ?? null,
    overall_status: state.overall_status,
    artifacts: Array.isArray(state.artifacts) ? state.artifacts : [],
    wechat_qr: {
      status: state.wechat_qr?.status || 'not_released',
      image: state.wechat_qr?.image ?? null,
    },
    public_surfaces: state.public_surfaces,
    verified_capabilities: state.verified_capabilities || [],
    known_limitations: state.known_limitations || [],
    tested_devices: state.tested_devices || [],
    evidence_ids: state.evidence_ids || [],
  };
}

function jsModuleSource(manifest) {
  return `/* Generated by scripts/generate-release-metadata.mjs — DO NOT EDIT */
export const RELEASE_METADATA = ${JSON.stringify(manifest, null, 2)};
export default RELEASE_METADATA;
`;
}

// F027 三线镜像：JSON 标量在 Dart/Kotlin 里同形（JSON 字符串转义规则兼容两语言），
// 集合递归展开为带缩进的字面量，保证与 uniapp 产物同源同序（manifest 键序固定）。
// Dart 侧额外用单引号字面量（flutter_lints prefer_single_quotes）并转义 $（插值）。
function dartString(value) {
  let out = '';
  for (const ch of value) {
    switch (ch) {
      case '\\':
        out += '\\\\';
        break;
      case "'":
        out += "\\'";
        break;
      case '$':
        out += '\\$';
        break;
      case '\n':
        out += '\\n';
        break;
      case '\r':
        out += '\\r';
        break;
      case '\t':
        out += '\\t';
        break;
      default: {
        const code = ch.codePointAt(0);
        out += code < 0x20 ? `\\u${code.toString(16).padStart(4, '0')}` : ch;
      }
    }
  }
  return `'${out}'`;
}

function dartLiteral(value, pad) {
  if (value === null) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return dartString(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '<dynamic>[]';
    const inner = value.map((v) => `${pad}  ${dartLiteral(v, `${pad}  `)},`).join('\n');
    return `<dynamic>[\n${inner}\n${pad}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) return '<String, dynamic>{}';
    const inner = entries
      .map(([k, v]) => `${pad}  ${dartString(k)}: ${dartLiteral(v, `${pad}  `)},`)
      .join('\n');
    return `<String, dynamic>{\n${inner}\n${pad}}`;
  }
  throw new Error(`dart emitter: 不支持的值类型 ${typeof value}`);
}

function dartModuleSource(manifest) {
  return `// Generated by scripts/generate-release-metadata.mjs — DO NOT EDIT.
// F027 版本元数据：apps/uniapp/config/release-metadata.generated.js 的 Dart 锁定镜像，
// 与 uniapp 产物出自同一确定性管线；版本唯一事实源 = 仓库根 VERSION。
const Map<String, dynamic> kReleaseMetadata = ${dartLiteral(manifest, '')};
`;
}

function kotlinLiteral(value, pad) {
  if (value === null) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return 'emptyList<Any?>()';
    const inner = value.map((v) => `${pad}  ${kotlinLiteral(v, `${pad}  `)},`).join('\n');
    return `listOf(\n${inner}\n${pad})`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) return 'emptyMap<String, Any?>()';
    const inner = entries
      .map(([k, v]) => `${pad}  ${JSON.stringify(k)} to ${kotlinLiteral(v, `${pad}  `)},`)
      .join('\n');
    return `mapOf(\n${inner}\n${pad})`;
  }
  throw new Error(`kotlin emitter: 不支持的值类型 ${typeof value}`);
}

function kotlinModuleSource(manifest) {
  return `// Generated by scripts/generate-release-metadata.mjs — DO NOT EDIT.
// F027 版本元数据：apps/uniapp/config/release-metadata.generated.js 的 Kotlin 锁定镜像，
// 与 uniapp 产物出自同一确定性管线；版本唯一事实源 = 仓库根 VERSION。
package com.smartble.core.config

val RELEASE_METADATA: Map<String, Any?> = ${kotlinLiteral(manifest, '')}
`;
}

function writeRel(rel, body) {
  const abs = resolve(ROOT, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, body, 'utf8');
}

function main() {
  const version = readVersion();
  const buildCode = readBuildCode();
  const state = applyOverrides(readJson('release/release-state.json'));
  const manifest = buildManifest(version, buildCode, state);

  const bodies = {
    [OUT_PATHS.manifest]: stableStringify(manifest),
    [OUT_PATHS.docsLatest]: stableStringify(manifest),
    [OUT_PATHS.appJson]: stableStringify(manifest),
    [OUT_PATHS.appJs]: jsModuleSource(manifest),
    [OUT_PATHS.appleJson]: stableStringify(manifest),
    [OUT_PATHS.flutterDart]: dartModuleSource(manifest),
    [OUT_PATHS.androidKotlin]: kotlinModuleSource(manifest),
  };

  if (CHECK) {
    const drifted = [];
    for (const [rel, expected] of Object.entries(bodies)) {
      const abs = resolve(ROOT, rel);
      if (!existsSync(abs)) {
        drifted.push(`${rel} (missing)`);
        continue;
      }
      // Compare committed content identity (LF): Windows autocrlf checkouts
      // carry CRLF bytes that would otherwise register as false drift.
      const actual = readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
      if (actual !== expected) drifted.push(rel);
    }
    if (drifted.length) {
      console.error('Release metadata drift detected:');
      for (const d of drifted) console.error(`  - ${d}`);
      process.exit(1);
    }
    console.log('generate-release-metadata --check PASS');
    return;
  }

  for (const [rel, body] of Object.entries(bodies)) {
    writeRel(rel, body);
  }
  console.log(`generate-release-metadata wrote ${Object.keys(bodies).length} files (app_version=${version})`);
}

try {
  main();
} catch (e) {
  console.error(e.message || e);
  process.exit(1);
}
